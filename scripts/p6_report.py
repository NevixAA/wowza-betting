"""Generate reports/P6_BARS_FOR_APPROVAL.md from the committed proposal, its evidence and the staking policy.

    python scripts/p6_report.py --proposal output/threshold_proposals/2026-11_<id>.json \
        [--previous <older proposal json>] [--out reports/P6_BARS_FOR_APPROVAL.md]

Every number comes from the files it reads (the proposal, output/threshold_proposals/bars_opt_serving/<month>.json,
output/bars_opt/study/cells.json, config/bankroll_policy.json cell_staking, the stake replay if present). Nothing
is typed. Nothing is applied: the owner approves entries by id + hash, src/threshold_apply writes them.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MS_LABEL = {"over25_over": "O/U 2.5 Over", "over25_under": "O/U 2.5 Under", "btts_yes": "BTTS Yes",
            "over15_over": "Over 1.5", "over35_over": "Over 3.5", "ht_over05_over": "HT Over 0.5",
            "ht_over15_over": "HT Over 1.5"}
COUNT_COLS = ["PROVEN", "PROMISING", "UNPROVEN_OWN", "UNPROVEN_BLEND", "OFF_NO_OWN_ESTIMATE", "OFF_NEGATIVE",
              "OFF_NO_VALUE", "OFF_THIN", "NO_PRICE_DATA"]


def _j(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def _pct(x):
    return "—" if x is None else f"{100 * float(x):+.1f}%"


def _num(x, nd=3):
    return "—" if x is None else f"{float(x):.{nd}f}"


def _ci(ci):
    if not ci or ci[0] is None:
        return "[—, —]"
    return f"[{100 * ci[0]:+.1f}%, {100 * ci[1]:+.1f}%]"


def cells_of(proposal: dict) -> dict:
    """{(track, mside, league): cell} from the proposal entries."""
    out = {}
    for e in proposal["entries"]:
        for c in ((e.get("proposed") or {}).get("bars_opt") or {}).values():
            out[(c["track"], c["mside"], c["league"])] = dict(c, _entry=e["entry_id"], _hash=e["entry_hash"])
    return out


def changes(new: dict, old: dict) -> list[str]:
    rows = []
    for k in sorted(set(new) | set(old)):
        n, o = new.get(k), old.get(k)
        name = f"{k[2]} · {k[0]} · {MS_LABEL.get(k[1], k[1])}"
        if o is None:
            rows.append(f"| {name} | — | {n['verdict']} | new cell ({n['config']}, bars {_num(n['valuable_th'])}) |")
        elif n is None:
            rows.append(f"| {name} | {o['verdict']} | OFF / not proposed | cell dropped |")
        else:
            diff = []
            if n["verdict"] != o["verdict"]:
                diff.append(f"verdict {o['verdict']} → {n['verdict']}")
            if n["config"] != o["config"]:
                diff.append(f"config {o['config']} → {n['config']}")
            for b in ("valuable_th", "marksman_th", "sniper_th"):
                if n.get(b) != o.get(b):
                    diff.append(f"{b.split('_')[0]} {_num(o.get(b))} → {_num(n.get(b))}")
            if diff:
                rows.append(f"| {name} | {o['verdict']} | {n['verdict']} | {'; '.join(diff)} |")
    return rows


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--proposal", required=True)
    ap.add_argument("--previous")
    ap.add_argument("--out", default=str(ROOT / "reports" / "P6_BARS_FOR_APPROVAL.md"))
    a = ap.parse_args(argv)
    prop = _j(Path(a.proposal))
    month = prop["month"]
    ev = _j(ROOT / "output" / "threshold_proposals" / "bars_opt_serving" / f"{month}.json")
    fams = ev["families"]
    study = _j(ROOT / "output" / "bars_opt" / "study" / "cells.json")
    pol = _j(ROOT / "config" / "bankroll_policy.json")
    staking = pol["cell_staking"]["cells"]
    replay_p = ROOT / "output" / "threshold_proposals" / "bars_opt_serving" / f"{month}_stake_replay.json"
    replay = _j(replay_p) if replay_p.exists() else None
    cells = cells_of(prop)
    rel = Path(a.proposal).resolve().relative_to(ROOT).as_posix()
    L = []
    L.append(f"# P6 — Per-league bars for owner approval ({month})")
    L.append("")
    L.append(f"Proposal **{prop['proposal_id']}**, proposal_hash `{prop['proposal_hash']}`, file `{rel}`. Status "
             f"{prop['status']}: {len(prop['entries'])} league × market entries. Nothing is applied until you approve; "
             "`src/threshold_apply` writes exactly the entries you name.")
    L.append("")
    L.append("Generated by `python scripts/p6_report.py` from the proposal, its evidence "
             f"(`output/threshold_proposals/bars_opt_serving/{month}.json`), the study (`output/bars_opt/study/`) and "
             "`config/bankroll_policy.json`. Built with `python scripts/bars_opt.py serving-cells --month "
             f"{month}` under the pre-registered protocol (reports/P4_BARS_OPTIMIZATION.md), unchanged; owner rule "
             "**\"Learned blend, own number\"** for thin leagues; no global bar anywhere (a league × market without an "
             "applied cell tips nothing: NO_LEAGUE_BAR).")
    L.append("")
    L.append("**Re-run 2026-11-10 on the current clean data**: Phase 2 predictions on the improved frame "
             "`8d973b3f2f1f04f7` (the clean team models' second refit, standard run 20261109T154317Z, new_format run "
             "20261109T162137Z), football-data entry prices refreshed by the P7 collection (output/collect/fd_raw, "
             "League One 2023-24 restored, to 2026-11-04), the identity map from the current loader, and the "
             "Standard first-half O/U prices joined (P7 item 2). Same SELECT/FINAL split, same configuration-count "
             "rule, no new tuning. The FINAL window (2026-09-01..11-08) was scored before (proposal "
             "TP-2026-11-09-c2414fcf); this is its re-scoring on the corrected inputs, so it is not a fresh test - "
             "the Clean Record from go-live is.")
    L.append("")
    L.append("**Nothing here is PROVEN unless the table says so.**")
    L.append("")
    L.append("## Go-live day: what you approve, in order")
    L.append("")
    L.append("1. Merge `prep/bars-serving` into data-truth-100 at go-live (it carries prep/no-global-bars, prep/bars-opt, "
             "prep/top3-league and prep/ht-bars-join, and is already merged with data-truth-100, so the merge is "
             "conflict-free on 2026-11-10). On its own, before step 3, it silences every tip.")
    L.append("2. **Re-approve the research lock** (RED on the branch by design: global gates removed, per-cell staking, "
             "predict.yml global threshold variables removed): `python -m src.research_lock --approve --by \"Nevo "
             "(owner)\" --note \"2026-11 go-live: bars_opt serving (no global bars, NO_LEAGUE_BAR), per-cell staking "
             f"'Paper + PROMISING small' ({len(staking)} staked cells, reports/P6_BARS_FOR_APPROVAL.md)\"`.")
    L.append(f"3. **Approve the entries** in `config/threshold_approvals.json` by entry_id + entry_hash (listed per "
             f"league below), with proposal_id / proposal_hash above. Then `python -m src.threshold_apply --proposal "
             f"{rel} --dry-run`, then without --dry-run.")
    arg = cells.get(("new_format", "btts_yes", "Argentina Primera Division"))
    if arg:
        L.append(f"4. Argentina Primera Division BTTS YES (PROTECTED, real money) keeps tipping only if "
                 f"`{arg['_entry']}` is approved: its cell is {arg['mode']} ({arg['config']}), {arg['verdict']}, "
                 f"{arg.get('wf_bets')} selection bets at {_pct(arg.get('wf_roi'))}.")
    else:
        L.append("4. **Argentina Primera Division BTTS YES (PROTECTED) has NO cell in this proposal**: it would stop "
                 "tipping. Owner decision needed before go-live.")
    L.append("5. **TOP-3 on** (owner 2026-11-09): repository variables `TOP3_FREEZE_LEAD_MIN = 120` and "
             "`TOP3_LEAGUE_ENABLED = true`, at go-live.")
    L.append("")
    L.append("**Standard Over 1.5**: owner-approved in principle 2026-11-09 as PAPER / UNPROVEN (no staking entry); "
             "approve by id + hash on go-live day.")
    L.append("")
    L.append("## Staking this season: \"Paper + PROMISING small\" (owner 2026-11-09)")
    L.append("")
    L.append("`config/bankroll_policy.json` → `cell_staking` (rebuilt from this proposal by "
             "`scripts/cell_staking_from_proposal.py`): only the cells below stake; every other cell is PAPER "
             "(stake 0, reason NO_REAL_STAKE_PAPER_NO_CELL_ENTRY), never inherited from its track. The PROTECTED "
             "Argentina BTTS entry is carried verbatim (VALUABLE multiplier 1.0 owner-confirmed 2026-11-09). "
             "Portfolio caps, drawdown throttle, paper leagues and the direction rule are unchanged. Cloudbet stays "
             "PAPER_ONLY.")
    L.append("")
    L.append("| Staked cell | State | Base fraction | Max odds | Tier multipliers S / M / V |")
    L.append("|---|---|---|---|---|")
    for k in sorted(staking):
        s = staking[k]
        tm = s.get("tier_multipliers") or {}
        mo = s.get("max_odds")
        L.append(f"| `{k}` | {s['state']} | {s['base_fraction']} | "
                 f"{mo if mo is not None else 'HARD ceiling (no cell range)'} | "
                 f"{tm.get('SNIPER')} / {tm.get('MARKSMAN')} / {tm.get('VALUABLE')} |")
    import sys as _sys
    _sys.path.insert(0, str(ROOT / "scripts"))
    import cell_staking_from_proposal as G
    held: list = []
    G.build_cells(prop, staking, pol, held)
    if held:
        L.append("")
        L.append("**Held on paper by an owner rule (decision for you):** " + ", ".join(f"`{h}`" for h in held) +
                 ". The proposal makes it PROMISING, but its track is held PAPER by an explicit owner rule (tracks → "
                 "paper_reason, e.g. owner 2026-11-02 \"new-format O/U Unders are paper-only until the clean retrain "
                 "passes per-league validation\"). A cell never lifts an owner hold; it stakes only if you lift it.")
    blocked = [k for k in staking if "|OVER35|" in k]
    if blocked:
        L.append("")
        L.append(f"Note: {', '.join(blocked)} sit on a BLOCKED track (Over 3.5); a block is never lifted by a cell entry.")
    if replay:
        L.append("")
        L.append(f"Stake replay: `output/threshold_proposals/bars_opt_serving/{month}_stake_replay.json` "
                 "(old-model probabilities; shows what gets staked, not future profit).")
    L.append("")
    L.append("## Cell counts")
    L.append("")
    L.append("| Track | Market | Chosen configuration | Basis | " + " | ".join(COUNT_COLS) + " |")
    L.append("|---|---|---|---|" + "---|" * len(COUNT_COLS))
    tot = defaultdict(int)
    import sys
    sys.path.insert(0, str(ROOT))
    from src.bars_opt import cells as C
    for r in C.counts(fams):
        row = {"PROVEN": r["PROVEN"], "PROMISING": r["PROMISING"], "UNPROVEN_OWN": r["UNPROVEN_OWN"],
               "UNPROVEN_BLEND": r["UNPROVEN_BLEND"], "OFF_NO_OWN_ESTIMATE": r[C.OFF_NO_OWN],
               "OFF_NEGATIVE": r[C.OFF_NEGATIVE], "OFF_NO_VALUE": r[C.OFF_NO_VALUE],
               "OFF_THIN": r[C.OFF_THIN_ALL], "NO_PRICE_DATA": r[C.NO_PRICE]}
        for k2, v in row.items():
            tot[k2] += v
        L.append(f"| {r['track']} | {MS_LABEL.get(r['mside'], r['mside'])} | `{r['chosen']}` | {r['config_basis']} | "
                 + " | ".join(str(row[c]) for c in COUNT_COLS) + " |")
    L.append("| **all** | | | | " + " | ".join(f"**{tot[c]}**" for c in COUNT_COLS) + " |")
    L.append("")
    L.append("Configuration = probability source | edge measure | max odds | min odds (RAW / BLEND / SHRINK / LEARNED; "
             "NONE|ALL = LEAGUE_WIDE). OFF no own estimate: fewer than 2 own bets at the VALUABLE bar (the bars "
             "would be the pooled curve: a stand-in, never served). OFF negative: the FINAL 95% CI entirely below 0. "
             "OFF no value: no positive bar. NO_PRICE_DATA: no real two-sided price before the month.")
    # HT: study-only
    ht = [s for s in study if s["mside"].startswith("ht_")]
    if ht:
        L.append("")
        L.append("## Half-time markets (study only, not served)")
        L.append("")
        L.append("Standard HT Over 0.5 / 1.5 now have real bet-time two-sided prices (P7 item 2), so the study scores "
                 "them. Production tips no HT market, so they never enter a serving proposal (src/bars_opt/cells."
                 "not_served_families); shown here for evidence.")
        L.append("")
        L.append("| League | Market | Config | Verdict | Reason | Bars V / M / S | Selection bets / ROI | FINAL bets / ROI / CI |")
        L.append("|---|---|---|---|---|---|---|---|")
        for s in sorted(ht, key=lambda x: (x["mside"], x["league"])):
            f = s.get("final") or {}
            L.append(f"| {s['league']} | {MS_LABEL[s['mside']]} | `{s.get('config')}` | {s.get('verdict')} | "
                     f"{s.get('reason') or ''} | {_num(s.get('valuable_th'))} / {_num(s.get('marksman_th'))} / "
                     f"{_num(s.get('sniper_th'))} | {'—' if s.get('wf_bets') is None else s.get('wf_bets')} / {_pct(s.get('wf_roi'))} | "
                     f"{'—' if f.get('bets') is None else f.get('bets')} / {_pct(f.get('roi'))} / {_ci(f.get('ci95'))} |")
    if a.previous:
        old = cells_of(_j(Path(a.previous)))
        ch = changes(cells, old)
        L.append("")
        L.append(f"## Changes against the previous proposal ({_j(Path(a.previous))['proposal_id']})")
        L.append("")
        if ch:
            L.append("| Cell | Before | Now | Change |")
            L.append("|---|---|---|---|")
            L.extend(ch)
        else:
            L.append("No cell changed.")
    L.append("")
    L.append("## Per league")
    L.append("")
    L.append("Bars: VALUABLE / MARKSMAN / SNIPER on the cell's measure. Selection = rows before the month at the "
             "VALUABLE bar (own bets / own ROI / blended ROI). FINAL = the study's 2026-09-01..11-08 check (bets / "
             "ROI / 95% CI).")
    off_by = defaultdict(list)
    for fam in fams:
        for o in fam["off"]:
            off_by[(o["league"], fam["track"])].append(f"{MS_LABEL.get(fam['mside'], fam['mside'])} = {o['reason']}")
    by_lg = defaultdict(list)
    for k, c in cells.items():
        by_lg[(c["league"], c["track"])].append(c)
    for (lg, tr) in sorted(set(by_lg) | set(off_by), key=lambda x: (x[1] != "new_format", x[0])):
        L.append("")
        L.append(f"### {lg} ({tr})")
        cs = sorted(by_lg.get((lg, tr), []), key=lambda c: c["mside"])
        if cs:
            L.append("")
            L.append("| Market | Config | Mode | Bars V / M / S | Odds | Verdict | Basis | Shrink w | Selection bets / ROI / blended | FINAL bets / ROI / CI |")
            L.append("|---|---|---|---|---|---|---|---|---|---|")
            for c in cs:
                f = c.get("study_final") or {}
                odds = ("any" if c.get("odds_max") is None and c.get("odds_min") is None else
                        f"{_num(c.get('odds_min'), 2)}–{_num(c.get('odds_max'), 2)}")
                fin = ("—" if not f.get("bets") else f"{f['bets']} / {_pct(f.get('roi'))} / {_ci(f.get('ci95'))}")
                L.append(f"| {MS_LABEL[c['mside']]} | `{c['config']}` | {c['mode']} | {_num(c['valuable_th'])} / "
                         f"{_num(c['marksman_th'])} / {_num(c['sniper_th'])} | {odds} | **{c['verdict']}** | "
                         f"{c['bar_basis']} | {_num(c.get('shrink_weight_at_valuable'), 2)} | {c.get('wf_bets')} / "
                         f"{_pct(c.get('wf_roi'))} / {_pct(c.get('wf_roi_shrunk'))} | {fin} |")
            ents = sorted({(c["_entry"], c["_hash"]) for c in cs})
            L.append("")
            L.append("Entries: " + "; ".join(f"`{e}` hash `{h[:16]}…`" for e, h in ents))
        if off_by.get((lg, tr)):
            L.append("")
            L.append("OFF: " + "; ".join(sorted(off_by[(lg, tr)])))
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {a.out}: {len(prop['entries'])} entries, {len(cells)} cells, {len(staking)} staked")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
