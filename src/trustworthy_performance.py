"""Trustworthy performance - three views that are never mixed (Phase 2 part 11 framework, 2026-11-06).

    python -m src.trustworthy_performance --dry-run       # row counts per view from the committed ledgers
    python -m src.trustworthy_performance --out FILE      # the full build; refused until the owner enables it

WHY. Earlier pages and reports pooled results of the unrepaired system, research tracks and (soon) the
repaired system into one ROI. Those are three different things. This module builds them as three
strictly separate views, and no function in it returns a number computed over rows of two views.

  A  HISTORICAL   settled live tips generated BEFORE the Clean Record start: produced by the UNREPAIRED
                  system. The corrections sidecars in output/corrections are applied and listed
                  (CORRECTIONS_A); each one says what it changed and how many rows.
  B  RESEARCH     shadow, paper and research tracks (player props are paper, the sharp tracker and the
                  weekly league panel are research). Never real-money, never part of A or C.
  C  FORWARD      the Clean Record: live tips generated by the repaired system on or after the go-live
                  start (config/trustworthy_performance.json clean_record_start_utc), on repaired data.
                  The start is set by the owner at go-live; while it is null view C is empty.

NUMBERS. Every cell carries the one Staked definition (src/staked.py: the policy recorded a stake > 0)
and, separately labelled, flat 1u over every settled tip. Each figure has n, matchdays and a matchday
block-bootstrap CI, and is NOT_ENOUGH_DATA below the owner's minimums (config; each copied from an
existing rule, never new). CLV is reported as stored, with its own minimum.

OWNER RULE. No new performance claims until the data is complete and the owner approves: the CLI runs
only --dry-run (row counts, no P/L) until `performance_claims_enabled` is true. Tests use synthetic data.
"""
from __future__ import annotations

import argparse
import json
import sys
import zlib
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CONFIG_FILE = ROOT / "config" / "trustworthy_performance.json"

A, B, C = "A_HISTORICAL", "B_RESEARCH", "C_FORWARD"
VIEWS = (A, B, C)
UNASSIGNED = "UNASSIGNED"
VIEW_LABEL = {
    A: "Historical: settled live tips produced by the UNREPAIRED system (before the Clean Record start), "
       "corrections sidecars applied",
    B: "Research: shadow, paper and research tracks (never real money)",
    C: "Forward (Clean Record): tips produced by the repaired system from the go-live start, on repaired data",
}
OK, NOT_ENOUGH = "OK", "NOT_ENOUGH_DATA"
SETTLED = ("WIN", "LOSS", "PUSH", "HALF_WIN", "HALF_LOSS")            # VOID is not a settled bet

#: live team ledgers (views A / C): (file, match-date column, generation-time column, market column)
LIVE_LEDGERS = (("bets_ledger.csv", "match_date", "generated_at", None),
                ("side_bets_ledger.csv", "match_date", "generated_at", "market"),
                ("ht_ledger.csv", "match_date", "generated_at", "market"))
#: research / paper sources (view B): (file, date column, pnl column, market column, kind)
RESEARCH_SOURCES = (("player_ledger.csv", "match_date", "pnl", "market", "paper: player props"),
                    ("sharp_ledger.csv", "match_date", "pnl", "market_label", "research: sharp tracker"),
                    ("league_weekly_research.csv", "match_date", "flat_pnl", "market",
                     "research: weekly league panel (every candidate)"))
#: player_ledger rows a props sidecar lists with exclude=True (dashboard_data.props_view.FLAG_FILES)
PROPS_FLAG_FILES = {"props_sentinel_prob.csv": "model probability was a cap value",
                    "props_ghost_tips.csv": "tip not tied to the player's real fixture"}


class MixedViewsError(ValueError):
    """A metric was asked for over rows of more than one view."""


# ── config ─────────────────────────────────────────────────────────────────────────────────────
def load_config(path=None) -> dict:
    return json.loads(Path(path or CONFIG_FILE).read_text(encoding="utf-8"))


def minimums(cfg: dict) -> dict:
    """{'settled', 'matchdays', 'clv'} -> int, read from the config; a missing value is an error."""
    m = cfg["minimums"]
    return {k: int(m[k]["value"]) for k in ("settled", "matchdays", "clv")}


def clean_record_start(cfg: dict) -> pd.Timestamp:
    """The owner's Clean Record start (UTC), or NaT while it is unset. A naive value is read as UTC."""
    v = cfg.get("clean_record_start_utc")
    if not v:
        return pd.NaT
    t = pd.Timestamp(v)
    return t.tz_convert("UTC") if t.tzinfo else t.tz_localize("UTC")


# ── reading ────────────────────────────────────────────────────────────────────────────────────
def _read(out_dir: Path, name: str) -> pd.DataFrame | None:
    p = Path(out_dir) / name
    if not p.exists():
        return None
    try:
        return pd.read_csv(p, low_memory=False)
    except Exception:                                                    # noqa: BLE001 - unreadable = absent
        return None


def _settled(d: pd.DataFrame, pnl_col: str = "pnl") -> pd.Series:
    res = d["result"].astype(str).str.strip().str.upper() if "result" in d.columns else pd.Series("", index=d.index)
    return res.isin(SETTLED) & pd.to_numeric(d.get(pnl_col), errors="coerce").notna()


def assign_live(d: pd.DataFrame, start: pd.Timestamp, gen_col: str = "generated_at",
                date_col: str = "match_date") -> pd.Series:
    """View of each live-ledger row: A before the start (or every row while the start is unset), C when
    generated AND played on or after it; a row without a generation time cannot be placed (UNASSIGNED)."""
    if pd.isna(start):
        return pd.Series(A, index=d.index, dtype=object)
    gen = pd.to_datetime(d.get(gen_col), errors="coerce", utc=True, format="mixed")
    day = pd.to_datetime(d.get(date_col), errors="coerce").dt.tz_localize("UTC")
    out = pd.Series(UNASSIGNED, index=d.index, dtype=object)
    out[gen.notna() & (gen < start)] = A
    out[gen.notna() & (gen >= start) & day.notna() & (day >= start.normalize())] = C
    return out


# ── corrections (view A) ───────────────────────────────────────────────────────────────────────
def _extra_time(d: pd.DataFrame, ledger: str, out_dir: Path) -> tuple[pd.DataFrame, dict]:
    """result / pnl restated on the 90-minute score from corrections/team_ledgers_extra_time_restated.csv
    (update_results.extra_time_restatement). Originals kept as result_stored / pnl_stored. A key listed
    twice is refused (counted)."""
    name = "team_ledgers_extra_time_restated.csv"
    info = {"sidecar": name, "applied_to": ledger, "effect": "result/pnl restated on 90 minutes",
            "present": False, "rows_changed": 0, "refused_ambiguous": 0}
    r = _read(Path(out_dir) / "corrections", name)
    if r is None or r.empty or "ledger" not in r.columns:
        return d, info
    info["present"] = True
    r = r[r["ledger"].astype(str) == ledger.replace(".csv", "")]
    mcol = "side" if ledger == "bets_ledger.csv" else "market"
    key = ["match_date", "league", "home_team", "away_team"]

    def k(f, mk):
        return (f[key].astype(str).apply(lambda s: s.str.strip()).agg("|".join, axis=1)
                + "|" + f[mk].astype(str).str.strip().str.upper())
    if r.empty or mcol not in d.columns:
        return d, info
    rk = k(r, "market")
    dup = rk.duplicated(keep=False)
    info["refused_ambiguous"] = int(dup.sum())
    r, rk = r[~dup], rk[~dup]
    res = dict(zip(rk, r["restated_result"].astype(str)))
    pnl = dict(zip(rk, pd.to_numeric(r["restated_pnl"], errors="coerce")))
    out = d.copy()
    out["result_stored"], out["pnl_stored"] = out.get("result"), out.get("pnl")
    dk = k(out, mcol)
    hit = dk.isin(res.keys())
    out.loc[hit, "result"] = dk[hit].map(res)
    out.loc[hit, "pnl"] = dk[hit].map(pnl)
    info["rows_changed"] = int((hit & (out["result"].astype(str) != out["result_stored"].astype(str))).sum())
    return out, info


def correct_live(d: pd.DataFrame, ledger: str, out_dir: Path) -> tuple[pd.DataFrame, list[dict]]:
    """A live ledger with the view-A corrections applied (never written back), and the list of what each
    sidecar did. `_excluded` marks rows kept out of every figure (reason in `_excluded_reason`)."""
    from src import clv_corrections as CC
    applied = []
    d = d.copy()
    d["_excluded"], d["_excluded_reason"] = False, ""
    d, et = _extra_time(d, ledger, out_dir)
    applied.append(et)
    if ledger in ("bets_ledger.csv", "side_bets_ledger.csv"):
        side = "side_clv_first_half_contaminated.csv" if ledger == "side_bets_ledger.csv" \
            else "clv_first_half_contaminated.csv"
        d = CC.exclude_contaminated_clv(d, out_dir)
        applied.append({"sidecar": side, "applied_to": ledger, "present": (Path(out_dir) / "corrections" / side).exists(),
                        "effect": "first-half close: CLV blanked (P/L kept)",
                        "rows_changed": int(d["clv_quarantined"].sum())})
    if ledger == "ht_ledger.csv":
        priced = CC.ht_priced_mask(d, out_dir)
        d.loc[~priced, "_excluded"] = True
        d.loc[~priced, "_excluded_reason"] = "HT tip without a market price (settled at the model's fair odds)"
        applied.append({"sidecar": "ht_ledger_unpriced.csv", "applied_to": ledger,
                        "present": (Path(out_dir) / "corrections" / "ht_ledger_unpriced.csv").exists(),
                        "effect": "unpriced HT rows excluded from P/L", "rows_changed": int((~priced).sum())})
    return d, applied


#: sidecars in output/corrections that view A lists but does not apply, and why
LISTED_NOT_APPLIED = {
    "bets_ledger_removed_backtest_rows_2026-11-01.csv": "rows already removed from bets_ledger; listed for audit",
    "stake_audit_reconciled.csv": "Staked is decided by src/staked.py on stake_audit / stake_plan records",
}


# ── statistics ─────────────────────────────────────────────────────────────────────────────────
def _seed(key: str) -> int:
    return zlib.crc32(key.encode("utf-8")) & 0xFFFFFFFF


def block_ci(num: np.ndarray, den: np.ndarray, days: np.ndarray, key: str, draws: int, ci: float):
    """CI of sum(num)/sum(den), resampling whole match dates. (None, None) below 2 dates."""
    days = np.asarray(days)
    u, inv = np.unique(days, return_inverse=True)
    if len(u) < 2:
        return None, None
    s = np.bincount(inv, weights=np.asarray(num, float))
    c = np.bincount(inv, weights=np.asarray(den, float))
    idx = np.random.default_rng(_seed(key)).integers(0, len(u), size=(draws, len(u)))
    tot = c[idx].sum(axis=1)
    with np.errstate(divide="ignore", invalid="ignore"):
        r = s[idx].sum(axis=1) / tot
    r = r[np.isfinite(r)]
    if not len(r):
        return None, None
    lo, hi = np.quantile(r, [(1 - ci) / 2, 1 - (1 - ci) / 2])
    return round(float(lo), 4), round(float(hi), 4)


def _status(n: int, days: int, min_n: int, min_days: int) -> str:
    return OK if n >= min_n and days >= min_days else NOT_ENOUGH


def metrics(frame: pd.DataFrame, cfg: dict, key: str) -> dict:
    """Staked, flat-1u and CLV figures of ONE view's settled rows. Refuses rows of two views."""
    views = set(frame["view"].dropna().unique()) if "view" in frame.columns else set()
    if len(views) > 1:
        raise MixedViewsError(f"{key}: rows of {sorted(views)} - views are never mixed in one number")
    mins, bs = minimums(cfg), cfg["bootstrap"]
    draws, ci = int(bs["draws"]), float(bs["ci"])
    from src import staked as S
    d = frame
    days = d["match_date"].astype(str).str[:10].to_numpy()
    pnl = pd.to_numeric(d["pnl"], errors="coerce").to_numpy()
    n, nd = len(d), len(set(days))
    flat = {"label": S.FLAT_LABEL, "n": n, "matchdays": nd,
            "pnl": round(float(np.nansum(pnl)), 4) if n else None,
            "roi": round(float(np.nansum(pnl) / n), 4) if n else None}
    flat["roi_ci"] = list(block_ci(pnl, np.ones(n), days, key + "|flat", draws, ci)) if n else [None, None]
    flat["status"] = _status(n, nd, mins["settled"], mins["matchdays"])
    st = (d["stake_status"] if "stake_status" in d.columns
          else pd.Series(S.NOT_POLICY, index=d.index)).astype(object)
    sm = S.is_staked(st).to_numpy()
    units = pd.to_numeric(d.get("stake_units"), errors="coerce").to_numpy() if "stake_units" in d.columns \
        else np.full(n, np.nan)
    ns, nds = int(sm.sum()), len(set(days[sm]))
    spnl, su = pnl[sm] * units[sm], units[sm]
    staked = {"label": S.DEFINITION, "short": S.SHORT, "n": ns, "matchdays": nds,
              "units": round(float(su.sum()), 4) if ns else None,
              "stake_pnl": round(float(spnl.sum()), 4) if ns else None,
              "roi": round(float(spnl.sum() / su.sum()), 4) if ns and su.sum() > 0 else None,
              "by_stake_status": {k: int((st == k).sum()) for k in S.STATUSES}}
    staked["roi_ci"] = list(block_ci(spnl, su, days[sm], key + "|staked", draws, ci)) if ns else [None, None]
    staked["status"] = _status(ns, nds, mins["settled"], mins["matchdays"])
    clv = pd.to_numeric(d.get("clv_pct"), errors="coerce") if "clv_pct" in d.columns else pd.Series(dtype=float)
    cm = clv.notna().to_numpy() if len(clv) else np.zeros(n, bool)
    nc, ndc = int(cm.sum()), len(set(days[cm])) if n else 0
    cv = clv.to_numpy()[cm] if nc else np.array([])
    out_clv = {"label": "clv_pct as stored (odds ratio, %), quarantined closes removed", "n": nc,
               "matchdays": ndc, "mean": round(float(cv.mean()), 4) if nc else None,
               "mean_ci": list(block_ci(cv, np.ones(nc), days[cm], key + "|clv", draws, ci)) if nc else [None, None],
               "status": _status(nc, ndc, mins["clv"], mins["matchdays"])}
    return {"flat_1u": flat, "staked": staked, "clv": out_clv}


# ── building the views ─────────────────────────────────────────────────────────────────────────
def frames(out_dir, cfg: dict) -> tuple[dict, list[dict]]:
    """{view: [(source name, kind, settled frame with `view`, n rows, n excluded)]}, corrections list.
    Only rows of the view's own sources enter it."""
    from src import clv_corrections as CC
    from src import staked as S
    out_dir = Path(out_dir)
    start = clean_record_start(cfg)
    records = S.load_records(out_dir)
    views: dict = {v: [] for v in VIEWS}
    views[UNASSIGNED] = []
    corrections: list[dict] = []
    for name, date_col, gen_col, _mk in LIVE_LEDGERS:
        d = _read(out_dir, name)
        if d is None or d.empty:
            continue
        if "source" in d.columns:
            d = d[d["source"].astype(str).str.strip().str.lower() == "live"]
        d = d.copy()
        d["view"] = assign_live(d, start, gen_col, date_col)
        labels = S.label_ledger(d, name, records)
        d = pd.concat([d, labels], axis=1)
        a_rows = d[d["view"] == A]
        if len(a_rows):
            a_rows, applied = correct_live(a_rows, name, out_dir)
            corrections += applied
        else:
            a_rows = a_rows.assign(_excluded=False, _excluded_reason="")
        rest = d[d["view"] != A].assign(_excluded=False, _excluded_reason="")
        for v in (A, C, UNASSIGNED):
            part = a_rows if v == A else rest[rest["view"] == v]
            keep = part[~part["_excluded"].astype(bool) & _settled(part)]
            views[v].append((name, "live", keep, int(len(part)), int(part["_excluded"].astype(bool).sum())))
    for name, date_col, pnl_col, mk, kind in RESEARCH_SOURCES:
        d = _read(out_dir, name)
        if d is None or d.empty:
            continue
        d = d.copy()
        d["_excluded"] = False
        if name == "sharp_ledger.csv":
            restated, info = CC.sharp_record(d, out_dir)
            corrections.append({"sidecar": "sharp_ledger_restated.csv", "applied_to": name,
                                "present": restated is not None, "effect": "P/L restated at the signal-time price",
                                "rows_changed": (int((pd.to_numeric(restated["pnl"], errors="coerce")
                                                      .ne(pd.to_numeric(restated["pnl_stored"], errors="coerce"))
                                                      & restated["pnl"].notna()).sum())
                                                 if restated is not None else 0),
                                "state": info.get("state")})
            if restated is None:
                d["_excluded"] = True                                    # under restatement: no figure
            else:
                d = restated.assign(_excluded=False)
        if name == "player_ledger.csv":
            for f, why in PROPS_FLAG_FILES.items():
                s = _read(out_dir / "corrections", f)
                n_hit = 0
                if s is not None and {"ledger_row", "exclude"} <= set(s.columns):
                    s = s[s["exclude"].astype(str).str.lower().eq("true")]
                    rows = d.index.intersection(pd.Index(pd.to_numeric(s["ledger_row"], errors="coerce").dropna()
                                                         .astype(int)))
                    if "player_name" in s.columns:
                        nm = dict(zip(pd.to_numeric(s["ledger_row"], errors="coerce"), s["player_name"].astype(str)))
                        rows = [i for i in rows if str(d.at[i, "player_name"]) == nm.get(i)]
                    d.loc[rows, "_excluded"] = True
                    n_hit = len(rows)
                corrections.append({"sidecar": f, "applied_to": name, "present": s is not None,
                                    "effect": f"excluded: {why}", "rows_changed": int(n_hit)})
        d["view"] = B
        d["pnl"] = pd.to_numeric(d[pnl_col], errors="coerce")
        d = pd.concat([d, S.label_ledger(d, name, records)], axis=1)
        keep = d[~d["_excluded"].astype(bool) & _settled(d)]
        views[B].append((name, kind, keep, int(len(d)), int(d["_excluded"].astype(bool).sum())))
    cdir = out_dir / "corrections"
    for f, why in LISTED_NOT_APPLIED.items():
        corrections.append({"sidecar": f, "applied_to": None, "present": (cdir / f).exists(),
                            "effect": f"listed, not applied: {why}", "rows_changed": 0})
    return views, corrections


def _group_cols(d: pd.DataFrame, name: str) -> list[str]:
    cols = [c for c in ("market", "model_type") if c in d.columns]
    if name == "bets_ledger.csv":
        cols = [c for c in ("side", "model_type") if c in d.columns]
    if name == "sharp_ledger.csv":
        cols = [c for c in ("market_label",) if c in d.columns]
    return cols


def build(out_dir, cfg: dict) -> dict:
    """The three views. Per view: per source and per source x market (x model type) cells; never a
    total across views, and never a total across the research sources of view B."""
    views, corrections = frames(out_dir, cfg)
    result = {"labels": VIEW_LABEL, "staked_definition": None, "minimums": cfg["minimums"],
              "owner_confirmed": bool(cfg.get("owner_confirmed")), "bootstrap": cfg["bootstrap"],
              "clean_record_start_utc": cfg.get("clean_record_start_utc"), "views": {},
              "corrections_view_A_and_B": corrections}
    from src import staked as S
    result["staked_definition"] = S.DEFINITION
    for v in VIEWS:
        out = {"label": VIEW_LABEL[v], "sources": {}}
        if v == C and not cfg.get("clean_record_start_utc"):
            out["status"] = "NOT_STARTED: clean_record_start_utc is not set (owner sets it at go-live)"
        for name, kind, d, n_rows, n_excl in views[v]:
            src = {"kind": kind, "rows": n_rows, "excluded_by_corrections": n_excl, "settled": int(len(d)),
                   "total": metrics(d, cfg, f"{v}|{name}"), "cells": []}
            gc = _group_cols(d, name)
            if gc and len(d):
                for k, g in d.groupby(gc, dropna=False, sort=True):
                    k = k if isinstance(k, tuple) else (k,)
                    src["cells"].append({**{c: (None if pd.isna(x) else str(x)) for c, x in zip(gc, k)},
                                         **metrics(g, cfg, f"{v}|{name}|{k}")})
            out["sources"][name] = src
        result["views"][v] = out
    result["unassigned"] = {name: {"rows": n_rows, "settled": int(len(d))}
                            for name, _k, d, n_rows, _e in views[UNASSIGNED]}
    return result


def dry_run(out_dir, cfg: dict) -> dict:
    """Row counts per view and source (rows, settled, excluded). No P/L, no ROI, no CLV."""
    views, corrections = frames(out_dir, cfg)
    return {"clean_record_start_utc": cfg.get("clean_record_start_utc"),
            "views": {v: {name: {"kind": kind, "rows": n_rows, "settled": int(len(d)),
                                 "excluded_by_corrections": n_excl}
                          for name, kind, d, n_rows, n_excl in views[v]} for v in (*VIEWS, UNASSIGNED)},
            "corrections": [{k: c[k] for k in ("sidecar", "applied_to", "present", "effect", "rows_changed")}
                            for c in corrections]}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="row counts per view only (no performance figures)")
    ap.add_argument("--out-dir", default=None, help="ledger directory (default config.OUTPUT_DIR)")
    ap.add_argument("--config", default=None)
    ap.add_argument("--out", default=None, help="write the full build here (JSON)")
    a = ap.parse_args(argv)
    cfg = load_config(a.config)
    if a.out_dir is None:
        import config
        out_dir = Path(config.OUTPUT_DIR)
    else:
        out_dir = Path(a.out_dir)
    if a.dry_run:
        print(json.dumps(dry_run(out_dir, cfg), indent=1, default=str))
        return 0
    if not cfg.get("performance_claims_enabled"):
        print("refused: performance_claims_enabled is false in config/trustworthy_performance.json - the owner "
              "enables the full build once the data is complete. Use --dry-run for row counts.", file=sys.stderr)
        return 2
    res = build(out_dir, cfg)
    text = json.dumps(res, indent=1, default=str)
    if a.out:
        Path(a.out).write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
