VERSION_FIELDS = ("model_version", "retrain_batch_id", "training_cutoff", "prediction_role")


def _version_fields(row, model_key: str | None) -> dict:
    """The attribution of one ledger row: from the stamped predictions row when present (the
    exact model predict loaded), else looked up for `model_key`. Never raises."""
    try:
        if str(row.get("model_version", "") or "") not in ("", "nan"):
            return {k: str(row.get(k, "") or "") for k in VERSION_FIELDS}
        from src import model_registry as reg
        if model_key:
            return dict(reg.stamp_for(model_key))
    except Exception:                                                 # noqa: BLE001
        pass
    return {"model_version": "UNKNOWN_LEGACY", "retrain_batch_id": "", "training_cutoff": "",
            "prediction_role": "CHAMPION"}


def _ou_key(model_type_tag, serving_recipe=None) -> str:
    """O/U row -> the model that scored it, including predict's fallbacks and the Standard O/U 2.5
    serving switch (`serving_recipe`, present on bets rows only when the switch is on)."""
    try:
        from src import model_registry as reg
        return reg.ou_model_for_row(str(model_type_tag), serving_recipe)
    except Exception as e:                                            # noqa: BLE001
        # Unknown model -> None, so the row is stamped UNKNOWN_LEGACY by _version_fields. This
        # returned "standard", attributing a new-format tip to the standard model.
        log.warning(f"Ledger: no model key for model_type {model_type_tag!r} ({e}) - attribution left unknown")
        return None


def _num(v) -> float:
    """A float from a predictions cell, or NaN when it is missing or not a number. Never 0.0: a
    missing edge/price/probability written as 0 reads as a real zero."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return np.nan
    return f if np.isfinite(f) else np.nan


def _af_fixture_id(v) -> int | str:
    """A positive integer API-Football fixture id from a bets cell, or '' (blank) when absent."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return ""
    return int(f) if np.isfinite(f) and f > 0 else ""


def _event_id(v) -> str:
    """The OddsAPI event id as sent, or '' (blank) when absent."""
    if v is None or (isinstance(v, float) and v != v):
        return ""
    s = str(v).strip()
    return "" if s in ("nan", "None", "<NA>") else s


def _fixture_identity(row) -> dict:
    return {"fixture_id": _af_fixture_id(row.get("fixture_id")),
            "oddsapi_event_id": _event_id(row.get("oddsapi_event_id", row.get("_oa_event_id")))}


def _warn_missing_identity(df: pd.DataFrame, ledger: str) -> None:
    missing = [c for c in ("fixture_id", "oddsapi_event_id") if c not in df.columns]
    if missing:
        log.warning(f"{ledger}: tips frame has no {missing} column(s) - those ids are left blank "
                    f"(src/betting.generate_bets must pass them through)")


def _pct(v: float):
    """round(v * 100, 2), or '' (blank cell) when v is missing."""
    return round(v * 100, 2) if np.isfinite(v) else ""


def _kelly_pct(edge: float, odds: float) -> float:
    """25% Kelly stake as % of bankroll."""
    if odds <= 1.0 or edge <= 0.0:
        return 0.0
    full_kelly = edge / (odds - 1.0)
    return round(full_kelly * 0.25 * 100, 2)


def _opening_odds(home: str, away: str, match_date: str, side: str) -> float | str:
    """
    Look up the first recorded odds snapshot for this fixture from odds_history_v9.json.
    Returns the odds value, or "" if not found.
    """
    if not config.ODDS_HISTORY_JSON.exists():
        return ""
    try:
        history = json.loads(config.ODDS_HISTORY_JSON.read_text(encoding="utf-8"))
        key = f"{home} vs {away} | {match_date}"
        snapshots = history.get(key, [])
        if not snapshots:
            return ""
        first = snapshots[0]
        field = "under" if side == "UNDER" else "over"
        val = first.get(field)
        return float(val) if val is not None else ""
    except Exception:
        return ""


def _load_ledger() -> pd.DataFrame:
    """Load ledger, backfilling missing 'source' column on old rows."""
    if LEDGER_FILE.exists():
        df = pd.read_csv(LEDGER_FILE, dtype=str)
        # A row without a source stays without one (NaN): it is not assumed to be a live tip, so
        # committed_sides / the dedup never count it as one. Every current row carries 'live'.
        if "source" not in df.columns:
            log.warning("bets_ledger.csv has no 'source' column - rows left without a source")
            df.insert(0, "source", np.nan)
        elif df["source"].isna().any():
            log.warning(f"bets_ledger.csv: {int(df['source'].isna().sum())} row(s) without a source - left blank")
        return df
    return pd.DataFrame(columns=LEDGER_COLS)


_TIER_RANK = {"SNIPER": 3, "MARKSMAN": 2, "VALUABLE": 1, "": 0, "AVOID": 0, "nan": 0}

# ── Later higher tiers: an append-only research log, never the ledger (2026-10-26) ─────────────
TIER_SEEN_NAME = "ledger_tier_seen.csv"     # beside the ledger it describes (output/)
TIER_SEEN_COLS = [
    "observed_at", "ledger", "source", "match_date", "home_team", "away_team", "selection",
    "observed_tier", "observed_edge_pct", "observed_odds",
    "ledger_tier", "ledger_edge_pct", "ledger_odds", "ledger_generated_at",
]
TIER_SEEN_KEY = ["ledger", "source", "match_date", "home_team", "away_team", "selection", "observed_tier"]


def tier_seen_store(path: Path | None = None):
    """First-sight store of tiers seen ABOVE a tip's logged tier: one row per (ledger, tip, observed
    tier), the first run that produced it. Research only - nothing reads it to tip, tier or stake."""
    from src.research.first_sight import FirstSightStore
    return FirstSightStore(path or (config.OUTPUT_DIR / TIER_SEEN_NAME), key=TIER_SEEN_KEY,
                           columns=TIER_SEEN_COLS, digest=True)


def _best_seen_tiers(ledger: str, path: Path | None = None) -> dict:
    """(source, match_date, home, away, selection) -> highest tier rank already in the research log."""
    try:
        d = tier_seen_store(path).read()
    except Exception:                                                 # noqa: BLE001
        return {}
    if d.empty:
        return {}
    d = d[d["ledger"].astype(str) == ledger]
    out: dict = {}
    for r in d.itertuples(index=False):
        k = (str(r.source), str(r.match_date)[:10], str(r.home_team), str(r.away_team), str(r.selection))
        out[k] = max(out.get(k, 0), _TIER_RANK.get(str(r.observed_tier), 0))
    return out


def _record_tiers_seen(rows: list, path: Path) -> int:
    """Append later-higher-tier observations. Never raises (a recorder must not stop predict)."""
    if not rows:
        return 0
    n = tier_seen_store(path).append(pd.DataFrame(rows, columns=TIER_SEEN_COLS))
    if n:
        log.info(f"Tier-seen log: {n} later higher tier(s) recorded (ledger tier unchanged) → {path.name}")
    return n


def _dedup_keys(df: pd.DataFrame) -> set:
    return set(zip(
        df.get("match_date", pd.Series([], dtype=str)).fillna(""),
        df.get("home_team",  pd.Series([], dtype=str)).fillna(""),
        df.get("away_team",  pd.Series([], dtype=str)).fillna(""),
        df.get("side",       pd.Series([], dtype=str)).fillna(""),
        df.get("source",     pd.Series([], dtype=str)).fillna(""),
    ))


def committed_sides(source: str = "live") -> dict:
    """(match_date, home, away) -> the side of the FIRST tip recorded for that fixture.

    ONE SIDE PER FIXTURE, FIRST TIP WINS (owner report 2026-10-11). The ledger used to dedup on
    (match_date, home, away, SIDE, source), so when the odds moved and the model's best side
    flipped, the opposite side was a "new" tip: Mito HollyHock v Shimizu was tipped UNDER 2.5
    MARKSMAN @1.89 on 2026-10-04 and OVER 2.5 VALUABLE @2.45 on 2026-10-11, and both were sent.
    67 fixtures carry both sides in the ledger (8 since 2026-09-01). A tip already sent stands.
    """
    led = _load_ledger()
    if led.empty:
        return {}
    led = led[led["source"].astype(str) == source].sort_values("generated_at", kind="mergesort")
    led = led.drop_duplicates(["match_date", "home_team", "away_team"], keep="first")
    return {(str(r.match_date)[:10], str(r.home_team), str(r.away_team)): str(r.side).strip()
            for r in led.itertuples()}


def drop_flipped(bets_df: pd.DataFrame, source: str = "live") -> pd.DataFrame:
    """Remove rows whose fixture already has a tip on the OTHER side. Used on the send source
    (bets.csv) so a flipped signal is never sent."""
    if bets_df is None or bets_df.empty:
        return bets_df
    first = committed_sides(source)
    side = bets_df.get("bet", bets_df.get("best_side")).astype(str).str.strip()
    keys = list(zip(bets_df["date"].astype(str).str[:10], bets_df["home_team"].astype(str),
                    bets_df["away_team"].astype(str)))
    flipped = [first.get(k, s) != s for k, s in zip(keys, side)]
    n = sum(flipped)
    if n:
        log.info(f"Flip guard: {n} tip(s) on the opposite side of an earlier tip — not sent")
    return bets_df[[not f for f in flipped]]


def append_tips(bets_df: pd.DataFrame, source: str = "live") -> None:
    """
    Append new tips into bets_ledger.csv - the PRODUCTION record of real tips only.
    Simulated backtest bets never enter it (4,115 stale rows from a 2026-05-21 backtest, never
    settled and partly duplicated, were removed 2026-11-01); backtests write their own files.
    Deduped on (match_date, home, away, side, source).
    """
    if source != "live":
        raise ValueError(f"bets_ledger.csv holds live tips only, got source={source!r}")
    if bets_df is None or bets_df.empty:
        return
    _warn_missing_identity(bets_df, "bets_ledger")

    existing = _load_ledger()
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M")
    # FIRST LOGGED TIER STANDS (owner decision 2026-10-26; see the module docstring). This used to
    # be "best tier wins": a re-see at a higher tier raised signal_tier in place, so results were
    # graded against a tier the owner was never sent. Now a higher tier on a re-see goes to the
    # append-only research log (ledger_tier_seen.csv) and signal_tier is never touched.
    # Edge, kelly and drift_signal are frozen at first log too (commit B, pending owner approval).
    tier_seen_path = LEDGER_FILE.parent / TIER_SEEN_NAME
    best_seen = _best_seen_tiers("ou25", tier_seen_path)
    tier_seen_rows = []

    key_to_idx = {}
    for i, r in existing.iterrows():
        k = (str(r["match_date"])[:10], str(r["home_team"]), str(r["away_team"]),
             str(r["side"]).strip(), str(r["source"]))
        key_to_idx[k] = i

    new_rows, batch_keys = [], set()
    # Fixture -> (side, row index) of its FIRST tip, for the flip guard below.
    _first = {}
    for i, r in existing[existing["source"].astype(str) == source].sort_values(
            "generated_at", kind="mergesort").iterrows():
        _first.setdefault((str(r["match_date"])[:10], str(r["home_team"]), str(r["away_team"])),
                          (str(r["side"]).strip(), i))
    if "notes" in existing.columns:
        existing["notes"] = existing["notes"].astype(object)
    flips = 0

    for _, row in bets_df.iterrows():
        side       = str(row.get("bet", row.get("best_side", ""))).strip()
        match_date = str(row["date"])[:10]
        home       = str(row["home_team"])
        away       = str(row["away_team"])
        dedup_key  = (match_date, home, away, side, source)
        tier       = str(row.get("signal_tier", ""))
        odds       = float(row["odds_under25"] if side == "UNDER" else row["odds_over25"])
        edge       = _num(row.get("best_edge"))      # NaN when missing, never 0.0

        if dedup_key in key_to_idx:
            # Already logged. The logged tier STANDS; a higher tier now is research information.
            i   = key_to_idx[dedup_key]
            cur = str(existing.at[i, "signal_tier"])
            rank = _TIER_RANK.get(tier, 0)
            seen_key = (source, match_date, home, away, side)
            if rank > max(_TIER_RANK.get(cur, 0), best_seen.get(seen_key, 0)):
                tier_seen_rows.append({
                    "observed_at": now, "ledger": "ou25", "source": source, "match_date": match_date,
                    "home_team": home, "away_team": away, "selection": side,
                    "observed_tier": tier, "observed_edge_pct": _pct(edge), "observed_odds": odds,
                    "ledger_tier": cur, "ledger_edge_pct": existing.at[i, "edge_pct"],
                    "ledger_odds": existing.at[i, "odds"],
                    "ledger_generated_at": existing.at[i, "generated_at"]})
                best_seen[seen_key] = rank
            continue
        if dedup_key in batch_keys:
            continue
        # FLIP GUARD: the fixture already has a tip on the other side. Not a new tip; the flip is
        # noted on the original row (once per side) so research can still see it.
        fx = (match_date, home, away)
        if fx in _first and _first[fx][0] != side:
            i = _first[fx][1]
            note = str(existing.at[i, "notes"]) if pd.notna(existing.at[i, "notes"]) else ""
            tag = f"FLIP_SEEN {side}"
            if tag not in note:
                existing.at[i, "notes"] = (note + " | " if note else "") +                     f"{tag} @{odds:.2f} {tier} {now}"
                flips += 1
            continue
        batch_keys.add(dedup_key)

        opening   = _opening_odds(home, away, match_date, side)
        drift_val = round(float(opening) - odds, 3) if isinstance(opening, (int, float)) else ""

        new_rows.append({
            "source":       source,
            "generated_at": now,
            "match_date":   match_date,
            "league":       str(row.get("league", "")),
            "home_team":    home,
            "away_team":    away,
            "side":         side,
            "odds":         odds,
            "opening_odds": opening,
            "odds_drift":   drift_val,
            "edge_pct":     _pct(edge),
            "signal_tier":  tier,
            "drift_signal": str(row.get("drift_signal", "")),
            # No edge -> no stake size (blank), not a Kelly computed from an invented 0 edge.
            "kelly_pct":    _kelly_pct(edge, odds) if np.isfinite(edge) else "",
            "model_type":   str(row.get("model_type", "")),
            "closing_odds": "",
            "clv_pct":      "",
            "result":       "",
            "pnl":          "",
            "notes":        "",
            **_version_fields(row, _ou_key(row.get("model_type", ""), row.get("serving_recipe"))),
            **_fixture_identity(row),
        })

    if flips:
        log.info(f"Ledger: {flips} side flip(s) noted on the original tip (not added as new tips)")
    _record_tiers_seen(tier_seen_rows, tier_seen_path)
    if not new_rows and not flips:
        log.info("Ledger: no new tips (all already logged).")
        return

    updated = (pd.concat([existing, pd.DataFrame(new_rows, columns=LEDGER_COLS)], ignore_index=True)
               if new_rows else existing)
    updated.to_csv(LEDGER_FILE, index=False)
    log.info(f"Ledger: {len(new_rows)} new tip(s); logged rows unchanged → {LEDGER_FILE}")


