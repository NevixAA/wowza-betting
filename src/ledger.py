def append_side_market_tips(side_df: pd.DataFrame, source: str = "live") -> None:
    """Append BTTS / Over 1.5 / Over 3.5 tips to their OWN ledger (side_bets_ledger.csv),
    one row per (fixture, market), ALL tiers. Same rule as append_tips: the FIRST logged tier stands,
    a later higher tier goes to the research log (ledger_tier_seen.csv), never into the row.

    This is the writer the weekly summary always expected but nothing populated — so side
    markets are now tracked for the season-long live test. result/pnl/closing_odds/clv fill
    in when a settling pass runs; until then rows are 'pending' and readers skip them
    (`_settled_only`), so an unsettled ledger never breaks a summary.
    """
    if side_df is None or side_df.empty:
        return
    existing = _load_side_ledger()
    now   = datetime.utcnow().strftime("%Y-%m-%d %H:%M")
    today = now[:10]
    tier_seen_path = SIDE_LEDGER_FILE.parent / TIER_SEEN_NAME
    best_seen = _best_seen_tiers("side", tier_seen_path)
    tier_seen_rows = []

    key_to_idx = {}
    for i, r in existing.iterrows():
        k = (str(r["match_date"])[:10], str(r["home_team"]), str(r["away_team"]),
             str(r["market"]), str(r["source"]))
        key_to_idx[k] = i

    new_rows, batch = [], set()
    for _, row in side_df.iterrows():
        market     = str(row.get("market", ""))
        match_date = str(row["date"])[:10]
        home       = str(row["home_team"])
        away       = str(row["away_team"])
        tier       = str(row.get("signal_tier", ""))
        # Missing price / edge / EV stay blank. They were written as 0, and settlement then read
        # an odds of 0 as "no price" only by luck while edge 0 / EV 0 read as real values.
        odds       = _num(row.get("market_odds"))
        odds       = odds if odds > 1.0 else ""
        edge_pct   = _pct(_num(row.get("edge")))
        ev_pct     = _pct(_num(row.get("ev")))
        key        = (match_date, home, away, market, source)

        if key in key_to_idx:
            # Already logged. The logged tier, odds, edge and ev STAND (2026-10-26): the row is settled
            # and CLV-graded at the price it was logged at. A higher tier is research info only.
            i   = key_to_idx[key]
            cur = str(existing.at[i, "signal_tier"])
            rank = _SIDE_RANK.get(tier, 0)
            seen_key = (source, match_date, home, away, market)
            if rank > max(_SIDE_RANK.get(cur, 0), best_seen.get(seen_key, 0)):
                tier_seen_rows.append({
                    "observed_at": now, "ledger": "side", "source": source, "match_date": match_date,
                    "home_team": home, "away_team": away, "selection": market,
                    "observed_tier": tier, "observed_edge_pct": edge_pct, "observed_odds": odds,
                    "ledger_tier": cur, "ledger_edge_pct": existing.at[i, "edge_pct"],
                    "ledger_odds": existing.at[i, "odds"],
                    "ledger_generated_at": existing.at[i, "generated_at"]})
                best_seen[seen_key] = rank
            continue
        if key in batch:
            continue
        batch.add(key)

        new_rows.append({
            "source": source, "generated_at": now, "signal_date": today,
            "match_date": match_date, "league": str(row.get("league", "")),
            "home_team": home, "away_team": away, "market": market,
            # The producer emits `side` and SIDE_LEDGER_COLS declares it, but it was never written
            # here, so the column was 100% null (Data Truth audit findings 26, 28).
            "side": (str(row["side"]) if pd.notna(row.get("side")) and str(row.get("side")).strip()
                     else _SIDE_OF_MARKET.get(market, "")),
            "odds": odds, "edge_pct": edge_pct, "ev_pct": ev_pct,
            "model_prob": (round(_num(row.get("model_prob")), 4)
                           if np.isfinite(_num(row.get("model_prob"))) else ""),
            "signal_tier": tier,
            "model_type": str(row.get("model_type", "")) or config.model_type_for_league(row.get("league", "")),
            "closing_odds": "", "clv_pct": "", "result": "", "pnl": "", "notes": "",
            # side rows are built from a column subset, so look the market's model up directly
            **_version_fields({}, market),
            # recorded by the producer (pipeline._generate_side_bets); blank when it did not say
            "threshold_source": (str(row["threshold_source"])
                                 if pd.notna(row.get("threshold_source")) else ""),
        })

    _record_tiers_seen(tier_seen_rows, tier_seen_path)
    if not new_rows:
        log.info("Side ledger: no new tips (all already logged).")
        return
    updated = pd.concat([existing, pd.DataFrame(new_rows, columns=SIDE_LEDGER_COLS)], ignore_index=True)
    updated.to_csv(SIDE_LEDGER_FILE, index=False)
    log.info(f"Side ledger: {len(new_rows)} new tip(s); logged rows unchanged → {SIDE_LEDGER_FILE}")


