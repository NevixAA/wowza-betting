"""
Bets Ledger — persistent record of every tip generated by the pipeline.

Appends new tips on each predict run. Never overwrites existing rows.
Deduplicates on (match_date, home_team, away_team, side, source).

Columns
-------
source        : "live" (real prediction) or "backtest" (walk-forward simulation)
generated_at  : timestamp of the predict/backtest run
match_date    : date the match is played
league        : league name
home_team     :
away_team     :
side          : OVER or UNDER
odds          : odds at time of generation
opening_odds  : first recorded odds from odds_history (before any drift)
odds_drift    : opening_odds - odds (how much the line moved by bet time)
edge_pct      : model edge in % (e.g. 7.5)
signal_tier   : VALUE or SNIPER
drift_signal  : Confirmed / Conflicted / Neutral / New
kelly_pct     : recommended stake as % of bankroll (25% Kelly)
model_type    : standard | new_format
closing_odds  : last recorded odds before kick-off (filled by update_results.py)
clv_pct       : closing line value %
result        : WIN / LOSS / VOID  ← fill manually after the match
pnl           : profit/loss in units ← fill manually (or leave blank for auto)
notes         : anything you want to remember about this bet

FIRST LOGGED TIER STANDS (owner decision 2026-10-26)
----------------------------------------------------
A tip's `signal_tier` is the tier it had when it was FIRST logged, which is the tier the owner
received (instant message from the same run, or the morning album, which reads this ledger). Until
2026-10-26 a later predict run with a higher tier raised the logged tier in place ("best tier
wins"), so results were reported against a tier nobody had been sent: first-sight tier matched the
ledger tier on only 72% of tips, and new-format BTTS read SNIPER +24.7% / MARKSMAN +16.0% /
VALUABLE +7.7% in the ledger against +52.2% / +3.1% / +6.7% at first-sight tier.

The same holds for the PRICE and EDGE of a logged tip (commit B, 2026-10-26, pending owner
approval): `odds`, `edge_pct`, `kelly_pct`, `drift_signal` (O/U) and `odds`, `edge_pct`, `ev_pct`
(side markets) are the values at first log. They used to be overwritten together with the tier
upgrade, so a side tip was SETTLED at a later run's price (92 of 619 side rows, +2.26u season to
date) and its CLV measured from it.

Now a later, higher tier (with that run's edge and odds) is recorded ONLY in the append-only research log
output/ledger_tier_seen.csv (one row per ledger x tip x observed tier, first sight of that tier;
src/research/first_sight.FirstSightStore). Nothing in a ledger row's tier changes after it is
written. EXISTING ROWS ARE NOT REWRITTEN: rows logged before 2026-10-26 may still carry an
upgraded tier. For tier analysis over that period use the first-sight data (the git history of
these ledgers, output/edge_engine_shadow.csv, src/research/edge_replay.first_sight), not the ledger.
"""
